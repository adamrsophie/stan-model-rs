//! Compiles every `tests/stan/*.stan` program of the workspace with stanc-rs into
//! `$OUT_DIR/<stem>.rs` and writes `$OUT_DIR/models.rs`, which declares one module per model.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dir = manifest.join("../../tests/stan");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    println!("cargo::rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|e| e == "stan"))
        .collect();
    files.sort();
    let mut index = String::new();
    for f in files {
        println!("cargo::rerun-if-changed={}", f.display());
        let stem = f.file_stem().unwrap().to_str().unwrap().to_string();
        let text = std::fs::read_to_string(&f).unwrap();
        let compiled = stanc_rs::compile_source(f.to_str().unwrap(), &text, &Default::default())
            .unwrap_or_else(|e| panic!("stanc-rs failed on {}:\n{e}", f.display()));
        std::fs::write(out.join(format!("{stem}.rs")), compiled.rust).unwrap();
        writeln!(
            index,
            "/// Generated by stanc-rs from `tests/stan/{stem}.stan`.\n\
             pub mod {stem} {{ include!(concat!(env!(\"OUT_DIR\"), \"/{stem}.rs\")); }}"
        )
        .unwrap();
    }
    std::fs::write(out.join("models.rs"), index).unwrap();
}
