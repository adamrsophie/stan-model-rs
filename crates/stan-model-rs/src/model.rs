//! The model traits and the evaluation drivers.
//!
//! [`StanModel`] is implemented by model code. Its log density is a generic function of the
//! scalar type, which is what automatic differentiation needs and what keeps the inner loops free
//! of dynamic dispatch. [`Model`] is the object-safe interface for inference algorithms; every
//! `StanModel` implements it through a blanket implementation that validates inputs, picks the
//! scalar type, and runs the stanmath-rs drivers.

use std::cell::RefCell;

use rand::Rng;
use stanmath_rs::Matrix;
use stanmath_rs::prelude::*;

use crate::meta::{ModelInfo, Outputs};
use crate::transform::{self, Bounds};
use crate::{Data, ErrorKind, ModelError, Result};

/// Options for evaluating the log density.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct LogDensityOptions {
    /// Add the log absolute Jacobian determinant of the constraining transforms, giving the
    /// density of the unconstrained parameters. Without it the value is the density of the
    /// constrained parameters evaluated at the transformed point (what optimization uses for
    /// maximum likelihood or MAP estimates).
    pub jacobian: bool,
    /// Drop constant terms (Stan's `propto`): `~` statements and `_lupdf`/`_lupmf` calls omit
    /// the terms that do not depend on parameters. Only terms that are constant in the
    /// parameters are dropped; `target +=` statements are always kept in full.
    pub propto: bool,
}

impl Default for LogDensityOptions {
    /// Jacobian included, constants kept: the full log density on the unconstrained space.
    fn default() -> Self {
        LogDensityOptions {
            jacobian: true,
            propto: false,
        }
    }
}

impl LogDensityOptions {
    /// Jacobian included, constants dropped: what Hamiltonian Monte Carlo uses.
    pub const SAMPLING: LogDensityOptions = LogDensityOptions {
        jacobian: true,
        propto: true,
    };
}

/// The interface implemented by model code (generated by stanc-rs or written by hand).
///
/// Implementations hold the data and transformed data, which are read and validated when the
/// model is constructed and never change afterwards. Every method takes `&self`, so a model can
/// be evaluated from several threads at once when it is `Sync`.
pub trait StanModel {
    /// Metadata, built once when the model is constructed.
    fn model_info(&self) -> &ModelInfo;

    /// The log density at unconstrained parameters `theta`, which has exactly
    /// [`ModelInfo::num_unconstrained`] values (the caller checks).
    ///
    /// The implementation constrains the parameters (adding the log Jacobian if `jacobian`),
    /// evaluates the transformed parameters and checks their constraints, and accumulates the
    /// model block. With `propto`, it uses the `_lupdf` forms for `~` statements; those drop
    /// terms only for arguments that carry no derivative information, so `propto` is only
    /// meaningful when `T` is an autodiff type ([`Model`] arranges this).
    fn log_prob<T: Real>(&self, theta: &[T], jacobian: bool, propto: bool) -> Result<T>;

    /// Constrained parameters, then (if requested) transformed parameters and generated
    /// quantities, each variable flattened in output order (see [`crate::meta`]). `theta` has
    /// exactly [`ModelInfo::num_unconstrained`] values.
    ///
    /// Generated quantities draw from `rng`. The default implementation constrains the
    /// parameters using the bounds in the metadata, and fails with
    /// [`ErrorKind::Unsupported`] if the model declares transformed parameters or generated
    /// quantities that are requested.
    fn write_array_impl(
        &self,
        theta: &[f64],
        outputs: Outputs,
        rng: &mut dyn Rng,
    ) -> Result<Vec<f64>> {
        let _ = rng;
        let info = self.model_info();
        let derived = info
            .outputs(outputs)
            .any(|v| v.block != crate::Block::Parameters);
        if derived {
            return Err(ModelError::new(
                ErrorKind::Unsupported,
                "the model does not implement transformed parameters or generated quantities",
            ));
        }
        constrain_parameters(info, |v| self.bounds(v), theta)
    }

    /// Unconstrained parameters from constrained parameter values in output order (exactly
    /// [`ModelInfo::num_outputs`] of [`Outputs::PARAMETERS`] values; the caller checks).
    ///
    /// The default frees each parameter with the bounds from [`StanModel::bounds`]. Models whose
    /// bounds depend on other parameters override it, freeing the parameters in declaration
    /// order so that each bound can be computed from the constrained values before it.
    fn unconstrain_impl(&self, constrained: &[f64]) -> Result<Vec<f64>> {
        let info = self.model_info();
        let mut out = Vec::with_capacity(info.num_unconstrained());
        let mut pos = 0;
        for v in info.parameters() {
            let n = v.num_constrained();
            let storage = v.to_storage_order(&constrained[pos..pos + n]);
            pos += n;
            out.extend(transform::free(v, &self.bounds(v)?, &storage)?);
        }
        Ok(out)
    }

    /// The bounds of a parameter. The default reads constant bounds from the metadata; models
    /// whose bounds depend on data override it.
    fn bounds(&self, var: &crate::VarInfo) -> Result<Bounds> {
        Bounds::from_metadata(var)
    }
}

/// Constrains every parameter of `info` and returns the values in output order.
///
/// A helper for [`StanModel::write_array_impl`] implementations.
pub fn constrain_parameters(
    info: &ModelInfo,
    bounds: impl Fn(&crate::VarInfo) -> Result<Bounds>,
    theta: &[f64],
) -> Result<Vec<f64>> {
    let mut reader = transform::Reader::new(theta);
    let mut out = Vec::with_capacity(info.num_outputs(Outputs::PARAMETERS));
    for v in info.parameters() {
        let x = reader.read(v, &bounds(v)?, None)?;
        out.extend(v.to_output_order(&x));
    }
    reader.finish()?;
    Ok(out)
}

/// The result of comparing a gradient with finite differences.
#[derive(Clone, Debug, PartialEq)]
pub struct GradientCheck {
    /// Log density.
    pub value: f64,
    /// Gradient by automatic differentiation.
    pub gradient: Vec<f64>,
    /// Gradient by central finite differences.
    pub finite_diff: Vec<f64>,
    /// Largest absolute difference relative to `max(1, |finite_diff|)`.
    pub max_rel_error: f64,
}

/// The object-safe model interface used by inference algorithms and services.
///
/// Implemented for every [`StanModel`]. All methods validate their inputs and return structured
/// errors; none panics on invalid input.
pub trait Model {
    /// Metadata.
    fn info(&self) -> &ModelInfo;

    /// Model name.
    fn name(&self) -> &str {
        &self.info().name
    }

    /// Number of unconstrained parameters.
    fn num_unconstrained(&self) -> usize {
        self.info().num_unconstrained()
    }

    /// Number of values [`Model::write_array`] returns for `outputs`.
    fn num_outputs(&self, outputs: Outputs) -> usize {
        self.info().num_outputs(outputs)
    }

    /// Flattened output names (`beta.1`, `Sigma.2.1`), in the order of [`Model::write_array`].
    fn param_names(&self, outputs: Outputs) -> Vec<String> {
        self.info().output_names(outputs)
    }

    /// Flattened names of the unconstrained parameters.
    fn unconstrained_param_names(&self) -> Vec<String> {
        self.info().unconstrained_names()
    }

    /// Log density at unconstrained parameters.
    fn log_density(&self, theta: &[f64], opts: LogDensityOptions) -> Result<f64>;

    /// Log density and its gradient at unconstrained parameters (reverse mode, one pass).
    fn log_density_gradient(
        &self,
        theta: &[f64],
        opts: LogDensityOptions,
    ) -> Result<(f64, Vec<f64>)>;

    /// Log density, writing its gradient into a caller-owned buffer `gradient` (which must have
    /// [`Model::num_unconstrained`] values). The evaluation itself still allocates its tape.
    fn log_density_gradient_into(
        &self,
        theta: &[f64],
        opts: LogDensityOptions,
        gradient: &mut [f64],
    ) -> Result<f64>;

    /// Log density, gradient, and Hessian (forward over reverse mode: `n` reverse passes for `n`
    /// parameters, `O(n)` times the cost of a gradient).
    fn log_density_hessian(
        &self,
        theta: &[f64],
        opts: LogDensityOptions,
    ) -> Result<(f64, Vec<f64>, Matrix<f64>)>;

    /// Hessian-vector product `H v` (forward over reverse mode: about twice the cost of a
    /// gradient, without forming `H`).
    fn log_density_hessian_vector_product(
        &self,
        theta: &[f64],
        v: &[f64],
        opts: LogDensityOptions,
    ) -> Result<Vec<f64>>;

    /// Compares the gradient with central finite differences of step `h`. A diagnostic; it costs
    /// `2n + 1` log density evaluations.
    fn check_gradient(
        &self,
        theta: &[f64],
        opts: LogDensityOptions,
        h: f64,
    ) -> Result<GradientCheck> {
        let (value, gradient) = self.log_density_gradient(theta, opts)?;
        let mut x = theta.to_vec();
        let mut finite_diff = Vec::with_capacity(theta.len());
        for i in 0..theta.len() {
            x[i] = theta[i] + h;
            let up = self.log_density(&x, opts)?;
            x[i] = theta[i] - h;
            let down = self.log_density(&x, opts)?;
            x[i] = theta[i];
            finite_diff.push((up - down) / (2.0 * h));
        }
        let max_rel_error = gradient
            .iter()
            .zip(&finite_diff)
            .map(|(g, f)| (g - f).abs() / f.abs().max(1.0))
            .fold(0.0, f64::max);
        Ok(GradientCheck {
            value,
            gradient,
            finite_diff,
            max_rel_error,
        })
    }

    /// Constrained parameters, then (if requested) transformed parameters and generated
    /// quantities, in output order. Generated quantities draw from `rng`.
    fn write_array(&self, theta: &[f64], outputs: Outputs, rng: &mut dyn Rng) -> Result<Vec<f64>>;

    /// The constrained parameters at `theta`, in output order.
    fn param_constrain(&self, theta: &[f64]) -> Result<Vec<f64>> {
        // Parameters alone never draw random numbers.
        let mut rng = crate::rng::stream(0, 0);
        self.write_array(theta, Outputs::PARAMETERS, &mut rng)
    }

    /// Unconstrained parameters from constrained parameter values in output order (the order of
    /// [`Model::param_names`] with parameters only).
    ///
    /// Fails with [`ErrorKind::Constraint`] if a value violates its declared constraint and
    /// with [`ErrorKind::Parameters`] if there are too few or too many values or if a value
    /// maps to a non-finite unconstrained value (for example a positive parameter set to 0).
    fn param_unconstrain(&self, constrained: &[f64]) -> Result<Vec<f64>>;

    /// Unconstrained parameters from constrained values given by name, in CmdStan's JSON format
    /// (for example user supplied initial values). Every parameter must be present.
    fn param_unconstrain_json(&self, values: &Data) -> Result<Vec<f64>> {
        // Bounds that depend on other parameters are handled by the model's unconstrain, which
        // receives all values at once.
        let mut flat = Vec::with_capacity(self.num_outputs(Outputs::PARAMETERS));
        for v in self.info().parameters() {
            let x = values.read(v).map_err(|e| ModelError {
                kind: ErrorKind::Parameters,
                ..e
            })?;
            flat.extend(v.to_output_order(&x));
        }
        self.param_unconstrain(&flat)
    }

    /// Initial values in Stan's way (`stan::services::util::initialize`): parameters present in
    /// `values` take the given constrained values, the others are drawn by constraining
    /// unconstrained values uniform in `(-radius, radius)`; the result is unconstrained.
    /// `radius = 0` gives zero for every missing parameter. Variables in `values` that are not
    /// parameters are ignored, as in Stan.
    ///
    /// This draws one candidate. Checking that its log density and gradient are finite, and
    /// retrying, is the services layer's job.
    fn param_initialize(&self, values: &Data, radius: f64, rng: &mut dyn Rng) -> Result<Vec<f64>> {
        if !(radius.is_finite() && radius >= 0.0) {
            return Err(ModelError::parameters(format!(
                "the initialization radius must be finite and non-negative, found {radius}"
            )));
        }
        let theta = random_unconstrained(self.num_unconstrained(), radius, rng);
        let mut constrained = self.param_constrain(&theta)?;
        let mut pos = 0;
        for v in self.info().parameters() {
            let k = v.num_constrained();
            if values.contains(&v.name) {
                let x = values.read(v).map_err(|e| ModelError {
                    kind: ErrorKind::Parameters,
                    ..e
                })?;
                constrained[pos..pos + k].copy_from_slice(&v.to_output_order(&x));
            }
            pos += k;
        }
        self.param_unconstrain(&constrained)
    }
}

fn check_len(theta: &[f64], n: usize, what: &str) -> Result<()> {
    if theta.len() != n {
        return Err(ModelError::parameters(format!(
            "expected {n} {what}, found {}",
            theta.len()
        )));
    }
    Ok(())
}

impl<M: StanModel> Model for M {
    fn info(&self) -> &ModelInfo {
        StanModel::model_info(self)
    }

    fn log_density(&self, theta: &[f64], opts: LogDensityOptions) -> Result<f64> {
        check_len(theta, self.num_unconstrained(), "unconstrained parameters")?;
        if opts.propto {
            // Dropping constants needs to know which values are parameters, which only autodiff
            // variables record.
            let r =
                try_value_and_grad(|p| StanModel::log_prob(self, p, opts.jacobian, true), theta)?;
            Ok(r.value)
        } else {
            StanModel::log_prob(self, theta, opts.jacobian, false)
        }
    }

    fn log_density_gradient(
        &self,
        theta: &[f64],
        opts: LogDensityOptions,
    ) -> Result<(f64, Vec<f64>)> {
        check_len(theta, self.num_unconstrained(), "unconstrained parameters")?;
        let r = try_value_and_grad(
            |p| StanModel::log_prob(self, p, opts.jacobian, opts.propto),
            theta,
        )?;
        Ok((r.value, r.gradient))
    }

    fn log_density_gradient_into(
        &self,
        theta: &[f64],
        opts: LogDensityOptions,
        gradient: &mut [f64],
    ) -> Result<f64> {
        check_len(theta, self.num_unconstrained(), "unconstrained parameters")?;
        check_len(gradient, self.num_unconstrained(), "gradient entries")?;
        let (value, g) = self.log_density_gradient(theta, opts)?;
        gradient.copy_from_slice(&g);
        Ok(value)
    }

    fn log_density_hessian(
        &self,
        theta: &[f64],
        opts: LogDensityOptions,
    ) -> Result<(f64, Vec<f64>, Matrix<f64>)> {
        check_len(theta, self.num_unconstrained(), "unconstrained parameters")?;
        // The stanmath-rs Hessian drivers take infallible functions; the first error is kept
        // here and the evaluation continues on a NaN until the driver returns.
        let error: RefCell<Option<ModelError>> = RefCell::new(None);
        let r = stanmath_rs::autodiff::value_grad_hessian(
            |p| match StanModel::log_prob(self, p, opts.jacobian, opts.propto) {
                Ok(v) => v,
                Err(e) => {
                    error.borrow_mut().get_or_insert(e);
                    Real::from_f64(f64::NAN)
                }
            },
            theta,
        );
        if let Some(e) = error.into_inner() {
            return Err(e);
        }
        Ok((r.value, r.gradient, r.hessian))
    }

    fn log_density_hessian_vector_product(
        &self,
        theta: &[f64],
        v: &[f64],
        opts: LogDensityOptions,
    ) -> Result<Vec<f64>> {
        let n = self.num_unconstrained();
        check_len(theta, n, "unconstrained parameters")?;
        check_len(v, n, "direction entries")?;
        let error: RefCell<Option<ModelError>> = RefCell::new(None);
        let hv = hessian_vector_product(
            |p| match StanModel::log_prob(self, p, opts.jacobian, opts.propto) {
                Ok(v) => v,
                Err(e) => {
                    error.borrow_mut().get_or_insert(e);
                    Real::from_f64(f64::NAN)
                }
            },
            theta,
            v,
        );
        if let Some(e) = error.into_inner() {
            return Err(e);
        }
        Ok(hv)
    }

    fn write_array(&self, theta: &[f64], outputs: Outputs, rng: &mut dyn Rng) -> Result<Vec<f64>> {
        check_len(theta, self.num_unconstrained(), "unconstrained parameters")?;
        let out = StanModel::write_array_impl(self, theta, outputs, rng)?;
        if out.len() != self.num_outputs(outputs) {
            return Err(ModelError::internal(format!(
                "write_array returned {} values; the metadata declares {}",
                out.len(),
                self.num_outputs(outputs)
            )));
        }
        Ok(out)
    }

    fn param_unconstrain(&self, constrained: &[f64]) -> Result<Vec<f64>> {
        let info = StanModel::model_info(self);
        check_len(
            constrained,
            info.num_outputs(Outputs::PARAMETERS),
            "constrained parameter values",
        )?;
        let out = StanModel::unconstrain_impl(self, constrained)?;
        if out.len() != info.num_unconstrained() {
            return Err(ModelError::internal(format!(
                "unconstrain returned {} values; the metadata declares {}",
                out.len(),
                info.num_unconstrained()
            )));
        }
        if let Some((i, bad)) = out.iter().enumerate().find(|(_, y)| !y.is_finite()) {
            let names = info.unconstrained_names();
            return Err(ModelError::parameters(format!(
                "the value is on the boundary of its constraint (unconstrained value {bad})"
            ))
            .with_variable(names[i].clone()));
        }
        Ok(out)
    }
}

/// Unconstrained values drawn uniformly from `(-radius, radius)`, Stan's default random
/// initialization with `radius = 2`. Retrying until the log density is finite is the
/// services layer's job.
pub fn random_unconstrained(n: usize, radius: f64, rng: &mut dyn Rng) -> Vec<f64> {
    (0..n)
        .map(|_| {
            let u: f64 = rand::RngExt::random(rng);
            radius * (2.0 * u - 1.0)
        })
        .collect()
}
